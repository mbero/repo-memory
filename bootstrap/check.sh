#!/usr/bin/env bash
# Knowledge base health check.
#
#   bootstrap/check.sh           run every check
#   bootstrap/check.sh --index   write docs/INDEX.md, then exit
#
# Exit 0 = healthy, 1 = at least one problem found.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

FAIL=0
WARN=0

red()  { printf '\033[31m%s\033[0m\n' "$*"; }
yel()  { printf '\033[33m%s\033[0m\n' "$*"; }
grn()  { printf '\033[32m%s\033[0m\n' "$*"; }

fail() { red "FAIL  $*"; FAIL=$((FAIL+1)); }
warn() { yel "WARN  $*"; WARN=$((WARN+1)); }

# The paths that belong to the knowledge base. No check reads another path,
# so project sources and dependency folders stay out of scope.
KB_PATHS="AGENTS.md CLAUDE.md GEMINI.md .github/copilot-instructions.md \
.github/instructions .github/prompts .cursor/rules .claude/commands .agents docs profiles"

kb_files() {
  local p
  for p in $KB_PATHS; do
    [ -e "$p" ] || continue
    find "./$p" -type f \( -name '*.md' -o -name '*.yml' -o -name '*.mdc' \)
  done | sort
}

doc_files() {
  [ -d docs ] && find ./docs -type f -name '*.md' | sort
}

# Template skeletons hold placeholders on purpose.
is_skeleton() {
  case "$1" in
    */_template/*|*/_template.md) return 0 ;;
    *) return 1 ;;
  esac
}

frontmatter() { sed -n '2,/^---$/p' "$1"; }

fm_value() { # fm_value FILE KEY
  frontmatter "$1" | grep -E "^$2:" | head -1 \
    | sed -e "s/^$2:[[:space:]]*//" -e 's/[[:space:]]*#.*$//' -e 's/^"//' -e 's/"$//'
}

fm_sources() { # one source entry per line
  frontmatter "$1" | awk '
    /^sources:[[:space:]]*\[/ {
      line = $0
      sub(/^sources:[[:space:]]*\[/, "", line); sub(/\].*$/, "", line)
      n = split(line, parts, ",")
      for (i = 1; i <= n; i++) print parts[i]
      next
    }
    /^sources:/ { inlist = 1; next }
    inlist && /^[[:space:]]+-[[:space:]]/ { sub(/^[[:space:]]+-[[:space:]]*/, ""); print; next }
    inlist && /^[A-Za-z_]+:/ { inlist = 0 }
  ' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^"//' -e 's/"$//'
}

to_epoch() {
  # Accepts YYYY-MM-DD. Works on both BSD (macOS) and GNU date.
  date -j -f "%Y-%m-%d" "$1" "+%s" 2>/dev/null || date -d "$1" "+%s" 2>/dev/null
}

# Print the document index. One row per document, sorted by path.
# The output depends only on the documents, so a second run gives the same text.
build_index() {
  local f rel title type status updated latest="" rows=""
  while IFS= read -r f; do
    is_skeleton "$f" && continue
    case "$f" in
      ./docs/INDEX.md|*/README.md|./docs/sessions/archive/*) continue ;;
    esac
    [ "$(head -1 "$f")" = "---" ] || continue
    rel="${f#./docs/}"
    title=$(fm_value "$f" title | tr '|' '/')
    type=$(fm_value "$f" type)
    status=$(fm_value "$f" status)
    updated=$(fm_value "$f" updated)
    rows="${rows}| [\`${rel}\`](${rel}) | ${title} | ${type} | ${status} | ${updated} |
"
    case "$updated" in
      [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9])
        if [ -z "$latest" ] || [ "$updated" \> "$latest" ]; then latest="$updated"; fi ;;
    esac
  done < <(doc_files)
  [ -z "$latest" ] && latest="1970-01-01"
  cat <<EOT
---
title: Knowledge base index
type: context
status: current
updated: ${latest}
sources: []
tags: [meta, index]
---

# Knowledge base index

Generated by \`bootstrap/check.sh --index\`. Do not edit this file by hand.

Read this file first. It lists every document with its title and its status.
Open a document only when its title matches the question.

| Document | Title | Type | Status | Updated |
|---|---|---|---|---|
EOT
  printf '%s' "$rows"
}

if [ "${1:-}" = "--index" ]; then
  [ -d docs ] || { echo "No docs/ folder in $ROOT" >&2; exit 1; }
  build_index > docs/INDEX.md
  echo "Wrote docs/INDEX.md"
  exit 0
fi

echo "Knowledge base check — $ROOT"
echo

# ---------------------------------------------------------------- 1. placeholders
if [ -f .template-source ]; then
  echo "[1/7] Unfilled placeholders — skipped (this is the template repository)"
else
  echo "[1/7] Unfilled placeholders"
  while IFS= read -r f; do
    is_skeleton "$f" && continue
    hits=$(grep -oE '\{\{[A-Z_]+\}\}' "$f" 2>/dev/null | sort -u | tr '\n' ' ')
    [ -n "$hits" ] && fail "$f — $hits"
  done < <(kb_files)
  if [ -f AGENTS.md ] && grep -q '| TBD |' AGENTS.md; then
    warn "AGENTS.md — a project fact still says TBD"
  fi
fi

# ---------------------------------------------------------------- 2. absolute paths
echo "[2/7] Absolute machine paths"
ABS='(/Users/[A-Za-z0-9._-]+/|/home/[A-Za-z0-9._-]+/|[A-Z]:\\Users\\)'
while IFS= read -r f; do
  line=$(grep -nE "$ABS" "$f" 2>/dev/null | head -1)
  [ -n "$line" ] && fail "$f:$line"
done < <(kb_files)

# ---------------------------------------------------------------- 3. frontmatter
echo "[3/7] Frontmatter in docs/"
VALID_TYPES="context decision knowledge lesson todo published analysis"
while IFS= read -r f; do
  [ "$(head -1 "$f")" = "---" ] || { fail "$f — no frontmatter block"; continue; }
  fm=$(frontmatter "$f")
  for key in title type status updated sources; do
    echo "$fm" | grep -qE "^${key}:" || fail "$f — frontmatter misses '${key}'"
  done
  t=$(fm_value "$f" type)
  case " $VALID_TYPES " in *" $t "*) ;; *) fail "$f — unknown type '$t'" ;; esac
  s=$(fm_value "$f" status)
  case "$s" in draft|current|superseded) ;; *) fail "$f — unknown status '$s'" ;; esac
done < <(doc_files)

# ---------------------------------------------------------------- 4. sources
# A source that names a repository path must exist. A URL, a log line, or a
# reference to another repository is not a local path, so the check skips it.
echo "[4/7] Source paths exist"
while IFS= read -r f; do
  is_skeleton "$f" && continue
  while IFS= read -r src; do
    [ -z "$src" ] && continue
    case "$src" in *"<"*|*"{{"*|*"://"*|*" "*) continue ;; esac
    path="${src%%#*}"
    path=$(printf '%s' "$path" | sed -E 's/:[0-9]+(-[0-9]+)?$//')
    case "$path" in */*|*.*) ;; *) continue ;; esac
    [ -e "$path" ] || fail "$f — source does not exist: $path"
  done < <(fm_sources "$f")
done < <(doc_files)

# ---------------------------------------------------------------- 5. stale drafts
echo "[5/7] Stale drafts (status: draft, older than 90 days)"
NOW=$(date "+%s")
while IFS= read -r f; do
  is_skeleton "$f" && continue
  [ "$(fm_value "$f" status)" = "draft" ] || continue
  d=$(fm_value "$f" updated)
  ep=$(to_epoch "$d") || continue
  [ -z "${ep:-}" ] && continue
  age=$(( (NOW - ep) / 86400 ))
  [ "$age" -gt 90 ] && warn "$f — draft for $age days"
done < <(doc_files)

# ---------------------------------------------------------------- 6. ADR index
echo "[6/7] ADR index"
if [ -f docs/decisions/README.md ]; then
  for adr in docs/decisions/[0-9][0-9][0-9][0-9]-*.md; do
    [ -e "$adr" ] || continue
    base=$(basename "$adr")
    grep -q "$base" docs/decisions/README.md || fail "docs/decisions/README.md — no index row for $base"
  done
fi

# ---------------------------------------------------------------- 7. document index
if [ -f .template-source ]; then
  echo "[7/7] Document index — skipped (bootstrap/init.sh generates it)"
else
  echo "[7/7] Document index"
  if [ ! -f docs/INDEX.md ]; then
    fail "docs/INDEX.md — missing. Run bootstrap/check.sh --index"
  elif ! build_index | diff -q - docs/INDEX.md >/dev/null 2>&1; then
    fail "docs/INDEX.md — out of date. Run bootstrap/check.sh --index"
  fi
fi

echo
if [ "$FAIL" -gt 0 ]; then
  red "$FAIL problem(s), $WARN warning(s)."
  exit 1
fi
grn "Healthy. $WARN warning(s)."
exit 0
